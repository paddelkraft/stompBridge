"""Generate a deterministic gzip-compressed C++ header for the device UI."""

from __future__ import annotations

import gzip
from pathlib import Path


try:
    Import("env")  # type: ignore[name-defined]  # Provided by PlatformIO/SCons.
    PROJECT_DIR = Path(env.subst("$PROJECT_DIR"))  # type: ignore[name-defined]
except NameError:
    PROJECT_DIR = Path.cwd()
OUTPUT = PROJECT_DIR / "include" / "web_ui_assets.h"
ASSETS = (
    ("IndexHtml", PROJECT_DIR / "ui" / "index.html"),
    ("StylesCss", PROJECT_DIR / "ui" / "styles.css"),
    ("AppJs", PROJECT_DIR / "ui" / "app.js"),
)


def format_bytes(data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), 16):
        rows.append("  " + ", ".join(f"0x{byte:02x}" for byte in data[offset : offset + 16]))
    return ",\n".join(rows)


def generate() -> None:
    sections = [
        "// Generated by scripts/embed_web_ui.py. Do not edit directly.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "namespace WebUiAssets {",
        "",
    ]
    for symbol, path in ASSETS:
        compressed = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        sections.extend(
            (
                f"inline constexpr uint8_t k{symbol}[] PROGMEM = {{",
                format_bytes(compressed),
                "};",
                f"inline constexpr size_t k{symbol}Length = sizeof(k{symbol});",
                "",
            )
        )
    sections.extend(("} // namespace WebUiAssets", ""))
    content = "\n".join(sections)
    if not OUTPUT.exists() or OUTPUT.read_text() != content:
        OUTPUT.write_text(content)


generate()
